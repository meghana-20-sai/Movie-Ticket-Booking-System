/**
 * Filter helpers for specific sections
 */
export const getFallbackByStatus = (status) => {
  if (status === 'coming-soon' || status === 'upcoming') {
    return DEFAULT_MOVIES.filter((m) => m.status === 'coming-soon' || m.releaseDate > '2026-10-01');
  }
  return DEFAULT_MOVIES.filter((m) => m.status === 'now-showing');
};

export const getFallbackByLanguage = (lang) => {
  const target = lang.toLowerCase();
  return DEFAULT_MOVIES.filter((m) => {
    const orig = (m.originalLanguage || '').toLowerCase();
    const langs = (m.languages || []).map((l) => l.toLowerCase());
    return orig === target || langs.includes(target);
  });
};

export const getFallbackByIndustry = (ind) => {
  const target = ind.toLowerCase();
  return DEFAULT_MOVIES.filter((m) => (m.industry || '').toLowerCase() === target);
};

export const getFallbackTopIMDb = () => {
  return [...DEFAULT_MOVIES].sort((a, b) => (parseFloat(b.imdbRating) || 0) - (parseFloat(a.imdbRating) || 0));
};
